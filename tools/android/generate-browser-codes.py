#!/usr/bin/env python3
"""Writes the engine's message codes for the Android app.

    tools/android/generate-browser-codes.py

The codes of browser commands, downloads, permission requests and the other
messages Summit's engine sends its browser are documented in the Haiku API
headers (Source/WebKit/UIProcess/API/haiku/WebKitContext.h and friends). The
Android app gets the same messages as JSON (webkit_summit_extensions_*), so it
uses the same numbers, written by this script into
android/app/src/main/java/works/airos/summit/extensions/BrowserCodes.kt.
build-engine.sh runs it; the output is checked in.
"""
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ENGINE = REPO / ".cache" / "WebKit" / "Source" / "WebKit" / "UIProcess" / "API" / "haiku"
HEADERS = ["WebKitContext.h", "WebKitView.h", "WebKitExtensionPermission.h"]
OUTPUT = REPO / "android" / "app" / "src" / "main" / "java" / "works" / "airos" / "summit" / "extensions" / "BrowserCodes.kt"


def value_of(text, previous):
    text = text.strip()
    if not text:
        return previous + 1
    m = re.fullmatch(r"'(.{4})'", text)
    if m:
        a, b, c, d = (ord(ch) for ch in m.group(1))
        return (a << 24) | (b << 16) | (c << 8) | d
    return int(text, 0)


def main():
    lines = []
    for header in HEADERS:
        source = (ENGINE / header).read_text(encoding="utf-8")
        for block in re.finditer(r"enum : uint32 \{([^}]*)\};", source):
            body = re.sub(r"//[^\n]*", "", block.group(1))
            previous = -1
            for entry in body.split(","):
                entry = entry.strip()
                if not entry:
                    continue
                name, _, raw = entry.partition("=")
                name = name.strip()
                if not re.fullmatch(r"B_WEBKIT_\w+", name):
                    continue
                previous = value_of(raw, previous)
                const = name[len("B_WEBKIT_"):]
                lines.append(f"  const val {const} = {previous - (1 << 32) if previous >= 1 << 31 else previous}")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    text = ("// Generated by tools/android/generate-browser-codes.py from the engine's\n"
            "// Haiku API headers (UIProcess/API/haiku/WebKitContext.h documents the messages). Do not edit.\n"
            "package works.airos.summit.extensions\n\n"
            "@Suppress(\"unused\")\nobject BrowserCodes {\n" + "\n".join(lines) + "\n}\n")
    if not OUTPUT.exists() or OUTPUT.read_text() != text:
        OUTPUT.write_text(text)
    print(f"{len(lines)} codes -> {OUTPUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
