#!/usr/bin/env python3
"""Writes src/core/StoreOfferLogo.h from resources/artwork/app.svg.

The card Summit shows on extension store pages (core/StoreOffer.cpp) draws
the Summit icon. Store pages forbid inline markup parsing (Trusted Types) and
may forbid data: images, so the icon goes in as a tree of SVG elements that
the card's script creates one by one: [tag, {attributes}, [children]]. Its
ids get a prefix, so they cannot meet the page's own.

    python3 tools/make-store-offer-logo.py
"""
import json
import pathlib
import re
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'resources/artwork/app.svg'
TARGET = ROOT / 'src/core/StoreOfferLogo.h'
PREFIX = 'summit-offer-logo-'
DROPPED_TAGS = {'title', 'desc'}
# The drawing (949 x 1083 units with its shadow, centred on 617, 660) fills
# little of its 1254-unit canvas; the card's small circle wants it larger.
VIEW_BOX = '67 110 1100 1100'
DROPPED_ATTRIBUTES = {'role', 'aria-label', 'aria-labelledby', 'width', 'height'}


def convert(element):
    tag = element.tag.split('}')[-1]
    attributes = {}
    for name, value in element.attrib.items():
        name = name.split('}')[-1]
        if name in DROPPED_ATTRIBUTES:
            continue
        if name == 'id':
            value = PREFIX + value
        if name == 'viewBox':
            value = VIEW_BOX
        value = re.sub(r'url\(#([^)]+)\)', lambda match: f'url(#{PREFIX}{match.group(1)})', value)
        attributes[name] = value
    children = [convert(child) for child in element if child.tag.split('}')[-1] not in DROPPED_TAGS]
    return [tag, attributes, children] if children else [tag, attributes]


def main():
    tree = convert(ET.parse(SOURCE).getroot())
    text = json.dumps(tree, separators=(',', ':'))
    TARGET.write_text(
        '#pragma once\n'
        '// Generated by tools/make-store-offer-logo.py from resources/artwork/app.svg.\n'
        '// The Summit icon as [tag, {attributes}, [children]] SVG elements.\n'
        'namespace summit {\n'
        f'inline constexpr const char* kStoreOfferLogo = R"logo({text})logo";\n'
        '}\n')
    print(f'{TARGET.relative_to(ROOT)}: {len(text)} bytes')


if __name__ == '__main__':
    main()
